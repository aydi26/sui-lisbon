# ── helpers ──────────────────────────────────────────────────────────────────
function Get-RelPath {
    param([string] $FullName)
    $rel = $FullName
    if ($FullName.StartsWith($RepoRoot, [System.StringComparison]::OrdinalIgnoreCase)) {
        $rel = $FullName.Substring($RepoRoot.Length).TrimStart('\', '/')
    }
    return ($rel -replace '\\', '/')
}

function Test-RootExists {
    param([string] $Rel)
    return (Test-Path -LiteralPath (Join-Path $RepoRoot $Rel))
}

function Get-GateFiles {
    param([string[]] $Roots, [string] $NameRegex)
    $out = New-Object System.Collections.ArrayList
    foreach ($r in $Roots) {
        $full = Join-Path $RepoRoot $r
        if (-not (Test-Path -LiteralPath $full)) { continue }
        $items = @(Get-ChildItem -LiteralPath $full -Recurse -File -Force -ErrorAction SilentlyContinue)
        foreach ($it in $items) {
            if ($it.FullName -match $ExcludeRx) { continue }
            if ($NameRegex -and ($it.Name -notmatch $NameRegex)) { continue }
            [void] $out.Add($it)
        }
    }
    return , $out.ToArray()
}

# Index at which a line's comment begins, or -1. `://` (URLs) is not a comment.
function Get-CommentStart {
    param([string] $Line, [string] $Ext)
    if ($Ext -eq '.md') { return 0 }
    $trim = $Line.TrimStart()
    if ($trim.StartsWith('*') -or $trim.StartsWith('/*')) { return 0 }
    $best = -1
    $m = [regex]::Match($Line, '(?<!:)//')
    if ($m.Success) { $best = $m.Index }
    if ($HashCommentExt -contains $Ext -or $Ext -eq '' -or $Ext -eq '.example') {
        $h = $Line.IndexOf('#')
        if ($h -ge 0 -and ($best -lt 0 -or $h -lt $best)) { $best = $h }
    }
    return $best
}

# Comment-blanked view of a file, LINE NUMBERING PRESERVED. Mirrors gates.sh `decomment`.
# The structural gates (notes / batchstate / keepercap / seal_le) parse this, never the raw
# text, so a banner that quotes the forbidden shape is not mistaken for the shape itself.
function Get-CodeLines {
    param([string] $FullPath)
    $lines = @()
    try { $lines = [System.IO.File]::ReadAllLines($FullPath) } catch { return @() }
    $out = New-Object string[] $lines.Length
    for ($i = 0; $i -lt $lines.Length; $i++) {
        $l = $lines[$i]
        if ($l.TrimStart().StartsWith('*')) { $out[$i] = ''; continue }
        $l = [regex]::Replace($l, '(?<!:)//.*$', '')
        $l = [regex]::Replace($l, '/\*.*$', '')
        $out[$i] = $l
    }
    return $out
}

function Find-Hits {
    param([object[]] $Files, [string] $Regex, [string[]] $AllowRx = @())
    $hits = New-Object System.Collections.ArrayList
    foreach ($f in $Files) {
        $rel = Get-RelPath $f.FullName
        $skip = $false
        foreach ($a in $AllowRx) { if ($rel -match $a) { $skip = $true; break } }
        if ($skip) { continue }
        $lines = $null
        try { $lines = [System.IO.File]::ReadAllLines($f.FullName) } catch { continue }
        $ext = $f.Extension.ToLowerInvariant()
        for ($i = 0; $i -lt $lines.Length; $i++) {
            $m = [regex]::Match($lines[$i], $Regex, [System.Text.RegularExpressions.RegexOptions]::IgnoreCase)
            if (-not $m.Success) { continue }
            $cs = Get-CommentStart $lines[$i] $ext
            $isComment = ($cs -ge 0 -and $m.Index -ge $cs)
            [void] $hits.Add([pscustomobject]@{
                    Rel       = $rel
                    Line      = $i + 1
                    Text      = $lines[$i].Trim()
                    IsComment = $isComment
                })
        }
    }
    return , $hits.ToArray()
}

function New-Result {
    param([string] $Name, [string] $Title, [string] $Status, [object[]] $Hits = @(), [string] $Note = '', [object[]] $Notes = @())
    return [pscustomobject]@{ Name = $Name; Title = $Title; Status = $Status; Hits = $Hits; Note = $Note; Notes = $Notes }
}

function New-Hit {
    param([string] $Rel, [int] $Line, [string] $Text)
    return [pscustomobject]@{ Rel = $Rel; Line = $Line; Text = $Text; IsComment = $false }
}

function New-SkipOrVerdict {
    param([string] $Name, [string] $Title, [string[]] $Roots, [object[]] $Files, [object[]] $Hits, [string] $Note)
    $present = @($Roots | Where-Object { Test-RootExists $_ })
    if ($present.Count -eq 0) {
        return (New-Result $Name $Title 'SKIP' @() ("NOTHING CHECKED — no scan root present: " + ($Roots -join ', ')))
    }
    $code = @($Hits | Where-Object { -not $_.IsComment })
    $comments = @($Hits | Where-Object { $_.IsComment })
    if ($Strict) { $code = @($Hits); $comments = @() }

    $scanned = "$($Files.Count) file(s) under $($present -join ', ')"
    if ($Note) { $scanned = "$scanned — $Note" }
    if ($comments.Count -gt 0) { $scanned = "$scanned · $($comments.Count) comment mention(s), not failing" }

    if ($code.Count -gt 0) { return (New-Result $Name $Title 'FAIL' $code $scanned $comments) }
    return (New-Result $Name $Title 'PASS' @() $scanned $comments)
}

