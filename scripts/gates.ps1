# G2 / INV-C1 — the exit destination is never a parameter; it is read from the pinned
# on-chain value. Two independent checks:
#   (a) `bitcoin_address` may appear only in carry.move (it composes hashi::withdraw)
#   (b) `exit_to_bitcoin`, WHEREVER it is declared — carry.move included, NO exemption —
#       must not take a destination parameter. (a) alone cannot catch that, because
#       carry.move is exempt from (a) by construction.
function Invoke-GateG2 {
    $roots = @('move/sources', 'keeper/src/execution', 'sdk/src/execution')
    $moveFiles = Get-GateFiles @('move/sources') $RxMove
    $tsFiles = Get-GateFiles @('keeper/src/execution', 'sdk/src/execution') $RxTs
    $hits = @()
    $hits += Find-Hits $moveFiles ([regex]::Escape('bitcoin_address')) @('^' + [regex]::Escape($CarryMove) + '$')
    $hits += Find-Hits $tsFiles ([regex]::Escape('bitcoinAddress')) @()

    # (b) the signature check — no exemption anywhere.
    $declared = 0
    foreach ($f in $moveFiles) {
        $rel = Get-RelPath $f.FullName
        foreach ($sig in (Get-FnSignatures $f.FullName 'exit_to_bitcoin')) {
            $declared++
            if (Test-ParamListNamesADestination $sig.Params) {
                $hits += (New-Hit $rel $sig.Line ("exit_to_bitcoin takes a destination parameter: (" + ($sig.Params -replace '\s+', ' ').Trim() + ")"))
            }
        }
    }
    $files = @($moveFiles) + @($tsFiles)
    $note = "$CarryMove exempt from the bitcoin_address scan (it composes hashi::withdraw); the exit_to_bitcoin signature check is NOT exempt"
    if ($declared -eq 0) { $note = "$note · no exit_to_bitcoin declared yet, so the signature check inspected nothing" }
    else { $note = "$note · $declared exit_to_bitcoin declaration(s) inspected" }
    return (New-SkipOrVerdict 'g2' 'No bitcoin-address parameter on any exit path' $roots $files $hits $note)
}

