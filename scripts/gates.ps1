# DESIGN-V2 §10 Notes — `struct Note` may declare NOTHING but `id` and `denom_index`.
# A `Balance`, an `amount`, or any other field would leak order size out of escrow no matter
# what is encrypted on top; the denomination ladder (§11) exists precisely so the struct can
# be this empty. `denom_index` is an index INTO the ladder, not a value.
function Invoke-GateNotes {
    $title = '`struct Note` declares only id + denom_index (no amount can leak)'
    $full = Join-Path $RepoRoot $NotesMove
    if (-not (Test-Path -LiteralPath $full)) {
        return (New-Result 'notes' $title 'SKIP' @() "NOTHING CHECKED — $NotesMove does not exist yet (v2 notes module has not landed)")
    }
    $lines = Get-CodeLines $full
    $hits = New-Object System.Collections.ArrayList
    $fields = @()
    $state = 0   # 0 = looking, 2 = decl seen / awaiting '{', 1 = inside body, 3 = done
    for ($i = 0; $i -lt $lines.Length -and $state -ne 3; $i++) {
        $l = $lines[$i]
        if ($state -eq 0) {
            if ($l -match 'struct\s+Note\b\s+has') { $state = if ($l -match '\{') { 1 } else { 2 } }
            continue
        }
        if ($state -eq 2) { if ($l -match '\{') { $state = 1 }; continue }
        # inside the body
        if ($l -match '\}') { $state = 3; continue }
        $t = $l.Trim()
        if (-not $t) { continue }
        $idx = $t.IndexOf(':')
        if ($idx -lt 1) { continue }
        $name = ($t.Substring(0, $idx) -replace '\s', '')
        $fields += $name
        if ($name -ne 'id' -and $name -ne 'denom_index') {
            [void] $hits.Add((New-Hit $NotesMove ($i + 1) $t))
        }
    }
    if ($state -eq 0) {
        return (New-Result 'notes' $title 'SKIP' @() "NOTHING CHECKED — $NotesMove exists but declares no ``struct Note``")
    }
    $note = "$NotesMove · fields found: " + $(if ($fields.Count) { $fields -join ', ' } else { '(none)' })
    if ($hits.Count -gt 0) { return (New-Result 'notes' $title 'FAIL' $hits.ToArray() "$note — a Note field other than id/denom_index leaks size out of escrow") }
    return (New-Result 'notes' $title 'PASS' @() $note)
}

# DESIGN-V2 §10 Batch — `.state =` may be written ONLY inside `set_state` and inside the
# struct literal built by `open_batch`. That single funnel is what makes
# OPEN -> SEALED -> CLEARING -> SETTLED provably monotonic: the assertions live in one
# function, so no other code path can move the machine sideways or backwards.
function Invoke-GateBatchState {
    $title = '`.state =` only inside set_state / open_batch (monotonic transitions)'
    $full = Join-Path $RepoRoot $BatchMove
    if (-not (Test-Path -LiteralPath $full)) {
        return (New-Result 'batchstate' $title 'SKIP' @() "NOTHING CHECKED — $BatchMove does not exist yet (v2 batch module has not landed)")
    }
    $lines = Get-CodeLines $full
    $hits = New-Object System.Collections.ArrayList
    $allow = $false; $pending = $false; $depth = 0; $writes = 0
    for ($i = 0; $i -lt $lines.Length; $i++) {
        $raw = $lines[$i]
        if (-not $allow -and -not $pending -and $raw -match 'fun\s+(set_state|open_batch)\s*[(<]') { $pending = $true }
        $ob = ([regex]::Matches($raw, '\{')).Count
        $cb = ([regex]::Matches($raw, '\}')).Count
        $wasAllowed = ($allow -or $pending)
        if ($pending -and $ob -gt 0) {
            $allow = $true; $pending = $false; $depth = $ob - $cb
            if ($depth -le 0) { $allow = $false }
        }
        elseif ($allow) {
            $depth += ($ob - $cb)
            if ($depth -le 0) { $allow = $false }
        }
        if ($raw -match '\.state\s*=(?!=)') {
            $writes++
            if (-not $wasAllowed) { [void] $hits.Add((New-Hit $BatchMove ($i + 1) $raw.Trim())) }
        }
    }
    $note = "$BatchMove · $writes ``.state =`` write(s) total, $($hits.Count) outside set_state/open_batch"
    if ($hits.Count -gt 0) { return (New-Result 'batchstate' $title 'FAIL' $hits.ToArray() $note) }
    return (New-Result 'batchstate' $title 'PASS' @() $note)
}

# ── Move signature parsing (shared by g2 and keepercap) ──────────────────────
# Returns every declaration of `fun <Name>` in a file with its PARAMETER LIST only — the
# text between the parenthesis that follows the function name and its match. Starting the
# scan at the function name (not at the first `(` in the line) is what keeps
# `public(package) fun allocate(...)` from being read as `(package)`; stopping at the
# matching close is what keeps a `: (u64, address)` RETURN TYPE out of the parameter list.
function Get-FnSignatures {
    param([string] $FullPath, [string] $Name)
    $out = @()
    $lines = Get-CodeLines $FullPath
    $rx = 'fun\s+' + [regex]::Escape($Name) + '\s*[(<]'
    for ($i = 0; $i -lt $lines.Length; $i++) {
        $m = [regex]::Match($lines[$i], $rx)
        if (-not $m.Success) { continue }
        # Accumulate from the function name forward until the parentheses balance.
        $buf = $lines[$i].Substring($m.Index)
        $j = $i
        while ($true) {
            $params = Get-ParamList $buf
            if ($null -ne $params) { $out += [pscustomobject]@{ Line = $i + 1; Params = $params }; break }
            $j++
            if ($j -ge $lines.Length -or ($j - $i) -gt 60) { break }
            $buf += "`n" + $lines[$j]
        }
    }
    return , $out
}

# Text between the first '(' and its matching ')', or $null if not yet balanced.
function Get-ParamList {
    param([string] $Text)
    $start = $Text.IndexOf('(')
    if ($start -lt 0) { return $null }
    $d = 0
    $sb = New-Object System.Text.StringBuilder
    for ($k = $start; $k -lt $Text.Length; $k++) {
        $c = $Text[$k]
        if ($c -eq '(') { $d++; if ($d -eq 1) { continue } }
        elseif ($c -eq ')') { $d--; if ($d -eq 0) { return $sb.ToString() } }
        if ($d -ge 1) { [void] $sb.Append($c) }
    }
    return $null
}

# INV-C1 (keepercap): does this parameter list name the `address` TYPE anywhere — bare, in a
# vector, in an Option, behind a reference? A keeper that cannot name a destination cannot send
# funds to one, so the whole invariant is "the word does not appear". Word-bounded, so a
# `&AdapterRegistry` or a `venue: ID` is not a false positive.
function Test-ParamListNamesAnAddressType {
    param([string] $Params)
    if ($null -eq $Params) { return $false }
    return ($Params -match '(^|[^A-Za-z0-9_])address([^A-Za-z0-9_]|$)')
}

# G2 (exit_to_bitcoin): strictly BROADER than the INV-C1 test, and deliberately so. The
# destination is read from the vault's pinned value, so NO parameter of this function may
# name a destination in any form — including `bitcoin_address: vector<u8>`, which the
# word-bounded test above misses because `_address` is one identifier.
function Test-ParamListNamesADestination {
    param([string] $Params)
    if ($null -eq $Params) { return $false }
    return ($Params -match '(?i)address|recipient|destination|payout_to|send_to')
}

# DESIGN-V2 §7 / INV-C1 — no KeeperCap-gated function may take an `address` parameter.
# The invariant is enforced by the ABSENCE of the parameter, which is exactly why a grep
# is the right enforcement and not a weak proxy for one.
function Invoke-GateKeeperCap {
    $title = 'No KeeperCap-gated function takes an address parameter (INV-C1)'
    $roots = @('move/sources')
    if (-not (Test-RootExists 'move/sources')) {
        return (New-Result 'keepercap' $title 'SKIP' @() 'NOTHING CHECKED — no scan root present: move/sources')
    }
    $files = Get-GateFiles $roots $RxMove
    $hits = New-Object System.Collections.ArrayList
    $found = @(); $missing = @()
    foreach ($name in $KeeperCallable) {
        $any = $false
        foreach ($f in $files) {
            $rel = Get-RelPath $f.FullName
            foreach ($sig in (Get-FnSignatures $f.FullName $name)) {
                $any = $true
                if (Test-ParamListNamesAnAddressType $sig.Params) {
                    [void] $hits.Add((New-Hit $rel $sig.Line ("$name takes an address parameter: (" + ($sig.Params -replace '\s+', ' ').Trim() + ")")))
                }
            }
        }
        if ($any) { $found += $name } else { $missing += $name }
    }
    if ($found.Count -eq 0) {
        return (New-Result 'keepercap' $title 'SKIP' @() ("NOTHING CHECKED — none of the 7 keeper-callable functions is declared yet: " + ($KeeperCallable -join ', ')))
    }
    $note = "checked: " + ($found -join ', ')
    if ($missing.Count -gt 0) { $note = "$note · NOT YET DECLARED (unchecked): " + ($missing -join ', ') }
    if ($hits.Count -gt 0) { return (New-Result 'keepercap' $title 'FAIL' $hits.ToArray() $note) }
    return (New-Result 'keepercap' $title 'PASS' @() $note)
}

# Every transaction goes through the devInspect-then-send wrapper, so a transaction that
# would revert is never broadcast. `signAndExecute` outside that one file means some path
# can broadcast blind.
function Invoke-GateSend {
    $title = 'signAndExecute only in ' + $SendTs + ' (devInspect-then-send)'
    $roots = @('keeper/src', 'sdk/src')
    if (-not (Test-Path -LiteralPath (Join-Path $RepoRoot $SendTs))) {
        return (New-Result 'send' $title 'SKIP' @() "NOTHING CHECKED — $SendTs does not exist yet, so there is no wrapper to funnel through (v2 keeper has not landed)")
    }
    $files = Get-GateFiles $roots $RxTs
    $allow = @('^' + [regex]::Escape($SendTs) + '$')
    # (?-i) forces CASE SENSITIVITY — PowerShell regex is case-insensitive by default,
    # so the bare word also matched the TYPE `SignAndExecute` and the injected field
    # `readonly signAndExecute?: SignAndExecute`. Neither is a call site, and flagging
    # them made the gate cry wolf on dependency injection.
    # `\s*\(` narrows it to an actual invocation, which is the only thing that can
    # broadcast a transaction without going through the devInspect wrapper.
    $hits = Find-Hits $files '(?-i)\bsignAndExecute\s*\(' $allow
    return (New-SkipOrVerdict 'send' $title $roots $files $hits 'a revert must never be broadcast')
}

# DESIGN-V2 §1 F1 — the deleted vault.move decoded the Seal identity epoch BIG-ENDIAN
# (`epoch = (epoch << 8) + byte`) while `bcs::peel_u64` reads LITTLE-ENDIAN. Copying that
# forward yields a policy that never opens, and it fails SILENTLY: the key server simply
# declines and the batch never reveals. Structural twin of the RECON R14 txid trap.
function Invoke-GateSealLe {
    $title = 'No big-endian u64 decode (`<< 8`) in ' + $BatchMove + ' (Seal identity is LE)'
    $full = Join-Path $RepoRoot $BatchMove
    if (-not (Test-Path -LiteralPath $full)) {
        return (New-Result 'seal_le' $title 'SKIP' @() "NOTHING CHECKED — $BatchMove does not exist yet (v2 batch module has not landed)")
    }
    $lines = Get-CodeLines $full
    $hits = New-Object System.Collections.ArrayList
    for ($i = 0; $i -lt $lines.Length; $i++) {
        if ($lines[$i] -match '<<\s*8\b') { [void] $hits.Add((New-Hit $BatchMove ($i + 1) $lines[$i].Trim())) }
    }
    $note = "$BatchMove · use bcs::peel_u64 (LITTLE-ENDIAN); see DESIGN-V2 §1 F1 and §3"
    if ($hits.Count -gt 0) { return (New-Result 'seal_le' $title 'FAIL' $hits.ToArray() $note) }
    return (New-Result 'seal_le' $title 'PASS' @() $note)
}

# Informational census — never fails (docs/CONVENTIONS.md §3).
function Invoke-GateTodo {
    $roots = @('move', 'keeper', 'sdk', 'app', 'scripts')
    $present = @($roots | Where-Object { Test-RootExists $_ })
    if ($present.Count -eq 0) {
        return (New-Result 'todo' 'TODO(Tx.y) census' 'SKIP' @() ("NOTHING CHECKED — no scan root present: " + ($roots -join ', ')))
    }
    $files = Get-GateFiles $roots $RxCode
    $tally = @{}
    $total = 0
    foreach ($f in $files) {
        $lines = $null
        try { $lines = [System.IO.File]::ReadAllLines($f.FullName) } catch { continue }
        foreach ($line in $lines) {
            foreach ($m in [regex]::Matches($line, 'TODO\(T\d+\.\d+\)')) {
                $id = $m.Value
                if ($tally.ContainsKey($id)) { $tally[$id] = $tally[$id] + 1 } else { $tally[$id] = 1 }
                $total++
            }
        }
    }
    $out = @()
    foreach ($k in ($tally.Keys | Sort-Object)) { $out += ("    {0,-14} {1}" -f $k, $tally[$k]) }
    $note = "$total marker(s) across $($tally.Keys.Count) task id(s) in $($files.Count) file(s) under $($present -join ', ')"
    return (New-Result 'todo' 'TODO(Tx.y) census (informational)' 'INFO' $out $note)
}

