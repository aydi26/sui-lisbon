}

$requested = @()
if (-not $Gate -or $Gate.Count -eq 0) { $requested = @($Registry.Keys) }
else {
    foreach ($g in $Gate) {
        $key = $g.ToLowerInvariant().TrimStart('-')
        if ($key -eq 'all') { $requested = @($Registry.Keys); break }
        if ($key -eq 'help' -or $key -eq '?') {
            Write-Host "gates.ps1 [$(($Registry.Keys) -join '|')|all] [-Strict]   (default: all)"
            Write-Host "  -Strict  a match in a comment fails too (literal 'string must not appear')"
            exit 0
        }
        if (-not $Registry.Contains($key)) {
            Write-Host "gates.ps1: unknown gate '$g'. Known: $(($Registry.Keys) -join ', '), all" -ForegroundColor Red
            exit 2
        }
        $requested += $key
    }
}
$requested = @($requested | Select-Object -Unique)

Write-Host ''
Write-Host 'Aphotic x Hashi — golden-rule gates' -ForegroundColor Cyan
Write-Host "  repo   : $RepoRoot"
Write-Host "  mode   : $(if ($Strict) { 'STRICT (comment mentions fail)' } else { 'default (comment mentions are notes)' })"
Write-Host ''

$results = @()
foreach ($key in $requested) {
    $r = & $Registry[$key]
    $results += $r

    $color = 'Gray'
    if ($r.Status -eq 'PASS') { $color = 'Green' }
    elseif ($r.Status -eq 'FAIL') { $color = 'Red' }
    elseif ($r.Status -eq 'SKIP') { $color = 'Yellow' }
    elseif ($r.Status -eq 'INFO') { $color = 'Cyan' }

    Write-Host ("[{0}] {1,-11} {2}" -f $r.Status.PadRight(4), $r.Name, $r.Title) -ForegroundColor $color
    if ($r.Note) { Write-Host ("       {0}" -f $r.Note) -ForegroundColor DarkGray }

    if ($r.Status -eq 'FAIL') {
        foreach ($h in $r.Hits) {
            $text = $h.Text
            if ($text.Length -gt 140) { $text = $text.Substring(0, 137) + '...' }
            Write-Host ("    {0}:{1}: {2}" -f $h.Rel, $h.Line, $text) -ForegroundColor Red
        }
    }
    elseif ($r.Status -eq 'INFO') {
        foreach ($h in $r.Hits) { Write-Host $h -ForegroundColor DarkCyan }
    }

    foreach ($n in $r.Notes) {
        $text = $n.Text
        if ($text.Length -gt 120) { $text = $text.Substring(0, 117) + '...' }
        Write-Host ("    note {0}:{1}: {2}" -f $n.Rel, $n.Line, $text) -ForegroundColor DarkGray
    }
}

$failCount = @($results | Where-Object { $_.Status -eq 'FAIL' }).Count
$passCount = @($results | Where-Object { $_.Status -eq 'PASS' }).Count
$skipCount = @($results | Where-Object { $_.Status -eq 'SKIP' }).Count

Write-Host ''
